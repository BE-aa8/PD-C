// Accessibility test for Claude's site (site/): axe-core on every tab, desktop and phone, in the chosen theme.
// Fails on any "serious" or "critical" violation; "moderate"/"minor" ones are listed but do not fail the run.
// axe-core is loaded from jsDelivr (pinned) at test time, so the repository has no npm dependency for it.
//
// Usage:
//   python3 -m http.server 8000 -d site &
//   node tests/browser-a11y.mjs --base http://localhost:8000          # also: --theme light
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, arr) => {
  if (a.startsWith('--')) acc.push([a.slice(2), arr[i + 1]]);
  return acc;
}, []));
const BASE = (args.base || 'http://localhost:8000').replace(/\/$/, '');
const THEME = args.theme === 'light' ? 'light' : 'dark';
const AXE = 'https://cdn.jsdelivr.net/npm/axe-core@4.10.2/axe.min.js';
const TABS = ['overview', 'simulator', 'theory', 'design', 'ai', 'video', 'refs'];
// Excluded from the scan, with the reason:
//  - Plotly's chart internals (.main-svg, the hidden hover layers): generated by the library; each chart is labelled by
//    its visible title and caption. The chart containers themselves stay in the scan.
//  - KaTeX's MathML copy (.katex-mathml) is visually hidden on purpose for screen readers; its colours are irrelevant.
const EXCLUDE = [['.js-plotly-plot .main-svg'], ['.js-plotly-plot .hoverlayer'], ['.katex-mathml']];

const browser = await chromium.launch();
const results = [];
for (const [label, opts] of [['desktop 1280', { viewport: { width: 1280, height: 900 } }], ['phone 375', { viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true }]]) {
  const page = await browser.newPage(opts);
  if (globalThis.__routeCdn) await globalThis.__routeCdn(page);
  await page.goto(`${BASE}/?theme=${THEME}#overview`, { waitUntil: 'networkidle' });
  await page.waitForTimeout(800);
  await page.addScriptTag({ url: AXE });
  for (const tab of TABS) {
    await page.click(`#tab-${tab}`);
    await page.waitForTimeout(tab === 'simulator' || tab === 'design' || tab === 'theory' ? 1500 : 600);
    // scan the open panel plus the page chrome (header, disclaimer, footer); hidden panels are skipped by axe
    const v = await page.evaluate(async (exclude) => {
      const r = await window.axe.run({ include: [['body']], exclude }, { resultTypes: ['violations'] });
      return r.violations.map((x) => ({ id: x.id, impact: x.impact, help: x.help, nodes: x.nodes.slice(0, 4).map((n) => n.target.join(' ')), count: x.nodes.length }));
    }, EXCLUDE);
    results.push({ where: `${label} · ${tab}`, v });
  }
  await page.close();
}
await browser.close();

let bad = 0;
console.log(`# Accessibility test (axe-core 4.10.2, theme ${THEME}) — ${BASE}/`);
for (const r of results) {
  const serious = r.v.filter((x) => x.impact === 'serious' || x.impact === 'critical');
  bad += serious.length;
  console.log(`${serious.length ? '❌' : '✅'} ${r.where}: ${r.v.length ? r.v.map((x) => `${x.id} (${x.impact}, ${x.count})`).join(', ') : 'no violations'}`);
  for (const x of r.v) console.log(`    · ${x.id}: ${x.help} → ${x.nodes.join(' | ')}`);
}
console.log(bad ? `${bad} serious/critical violation(s)` : 'No serious or critical violations');
process.exit(bad ? 1 : 0);
